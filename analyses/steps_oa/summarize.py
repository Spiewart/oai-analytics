def reconcile(run: Run) -> str:
    lt = lin_term(run)
    pairs = [
        (
            "P1",
            "p1",
            "roa",
            "periods_roa" if ("periods_roa", "knees") in run.flow else "horizon_roa",
        ),
        (
            "P2",
            "p2",
            "soa",
            "periods_soa" if ("periods_soa", "knees") in run.flow else "horizon_soa",
        ),
    ]
    if run.info.get("variant") == "by_horizon":
        pairs = [("P1", "p1", "roa", "horizon_roa"), ("P2", "p2", "soa", "horizon_soa")]
    lines = ["**Model n against the flow** (Model 1, linear term):", ""]
    lines.append(
        "| Model | Flow knees | Missing a covariate | Dropped (separation) | Model n | Events |"
    )
    lines.append("|---|---|---|---|---|---|")
    for label, t, outc, sample in pairs:
        r = run.row(t, outcome=outc, term=lt, model="m1")
        if r is None:
            continue
        flow_n = run.flow.get((sample, "knees_known"), run.flow.get((sample, "knees")))
        n, dr = int(r["n"]), int(r["dropped"])
        lines.append(
            f"| {label} | {n0(flow_n)} | {n0(flow_n - n - dr)} | {dr} | {n0(n)} | {r['events']} |"
        )
    lines.append("")
    lines.append(
        '"Dropped" knees sit in a level of a factor term (visit, span, or KL grade in Model 2) '
        "with no events or no non-events; they are left out so the GEE converges, and every "
        "table carries the count in its `dropped` column."
    )
    return "\n".join(lines)


def bands_table(run: Run, table: str, outcome: str) -> list[str]:
    out = [
        "| Steps/day at 48 months | Knees / events | Model 1 OR | Model 2 OR |",
        "|---|---|---|---|",
    ]
    for b in BANDS:
        r1 = run.row(table, outcome=outcome, term=f"band_{b}", model="m1")
        r2 = run.row(table, outcome=outcome, term=f"band_{b}", model="m2")
        out.append(f"| {BAND_LABEL[b]} | {nev(r1)} | {ci(r1)} | {ci(r2)} |")
    return out


def primary_section(run: Run) -> list[str]:
    lt = lin_term(run)
    out = ["### Primary: P1 and P2 (odds ratio per 1,000 steps/day at 48 months)", ""]
    out.append("| Estimate | Knees / events | Model 1 | Model 2 | Non-linearity p (M1, M2) |")
    out.append("|---|---|---|---|---|")
    for label, t, oc in (
        ("**P1**, incident ROA to 96 months", "p1", "roa"),
        ("**P2**, incident SOA to 96 months", "p2", "soa"),
        ("P2 in knees with ROA at 48 months", "p2", "soa_roa48"),
        ("P2 in knees without ROA at 48 months", "p2", "soa_noroa48"),
    ):
        r1 = run.row(t, outcome=oc, term=lt, model="m1")
        r2 = run.row(t, outcome=oc, term=lt, model="m2")
        p1 = run.row(t, outcome=oc, term="nonlinear_p", model="m1")
        p2 = run.row(t, outcome=oc, term="nonlinear_p", model="m2")
        ps = ", ".join(
            f"{num(p['estimate']):.2f}" if p and num(p["estimate"]) is not None else "—"
            for p in (p1, p2)
        )
        out.append(f"| {label} | {nev(r1)} | {ci(r1)} | {ci(r2)} | {ps} |")
    out.append("")
    for label, t, oc in (
        ("P1, incident ROA", "p1", "roa"),
        ("P2, incident SOA", "p2", "soa"),
        ("P2, knees with ROA at 48 months", "p2", "soa_roa48"),
        ("P2, knees without ROA at 48 months", "p2", "soa_noroa48"),
    ):
        out.append(f"**Step bands, {label}** (reference < 5,000):")
        out.append("")
        out.extend(bands_table(run, t, oc))
        out.append("")
    out.append(
        "**Spline curves** (Model 1; OR against 5,000 steps/day; `curve_p1.csv`, `curve_p2.csv`):"
    )
    out.append("")
    at = ["2500", "7500", "10000", "12500"]
    out.append("| Outcome | " + " | ".join(f"{int(a):,}" for a in at) + " |")
    out.append("|---|" + "---|" * len(at))
    for label, name in (("P1, ROA", "p1"), ("P2, SOA", "p2")):
        cv = {r["steps"]: r for r in run.curve(name)}
        cells = []
        for a in at:
            r = cv.get(a)
            if r is None or num(r["or"]) is None:
                cells.append("—")
            else:
                cells.append(f"{num(r['or']):.2f} ({num(r['lo']):.2f}–{num(r['hi']):.2f})")
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    out.append("")
    prim = [
        r
        for t in ("p1", "p2")
        for r in run.tables.get(t, [])
        if r["term"] != "nonlinear_p" and excludes_null(r) is not None
    ]
    hits = [r for r in prim if excludes_null(r)]
    out.append(
        f"**CIs that exclude the null across the primary displays** (P1, P2 and the P2 split; "
        f"linear and band terms; both models): {len(hits)} of {len(prim)} "
        f"(about {0.05 * len(prim):.1f} by chance). They are: "
        + "; ".join(
            f"{r['table'].upper()} {r['outcome']} {r['term'].replace('band_', 'band ')} "
            f"Model {r['model'][1]} {ci(r)}"
            for r in hits
        )
        + "."
    )
    out.append("")
    agree = {
        r["level"]: int(r["n"]) for r in run.desc if r["table"] == "agreement_kl_incident_roa99"
    }
    if agree:
        out.append(
            f"**Check:** KL 0–1 → 2+ from the readings agrees with OUTCOMES99 incident ROA in every "
            f"knee with both: {agree.get('true/true', 0)} incident in both, "
            f"{agree.get('true/false', 0) + agree.get('false/true', 0)} discordant, "
            f"{n0(agree.get('false/false', 0))} incident in neither."
            if agree.get("true/false", 0) + agree.get("false/true", 0) == 0
            else f"**Check:** KL 0–1 → 2+ vs OUTCOMES99 incident ROA: {agree}."
        )
        out.append("")
    return out


