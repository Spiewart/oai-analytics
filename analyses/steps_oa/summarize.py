def secondary_section(run: Run) -> list[str]:
    out = [
        "### Secondary families",
        "",
        "Odds ratios (Cox hazard ratios for knee replacement; differences in mm for JSW change) "
        'per 1,000 steps/day. "Change 48 → 72" is per 1,000 steps/day of change, in a model '
        "that also holds steps at 48 months, in people valid at both waves. **Every change model "
        "measures its outcome from 72 months onward** (S1, the 72-month Cox models in S2 and S3, "
        "and S3b's 72 → 96-month JSW).",
        "",
        "| Outcome | Term | Knees / events | Model 1 | Model 2 |",
        "|---|---|---|---|---|",
    ]
    for t in SECONDARY:
        seen = []
        for r in run.tables.get(t, []):
            key = (r["outcome"], r["term"])
            if key in seen or r["term"] == "events" or r["term"].startswith("band_"):
                continue
            seen.append(key)
            r1 = run.row(t, outcome=r["outcome"], term=r["term"], model="m1")
            r2 = run.row(t, outcome=r["outcome"], term=r["term"], model="m2")
            label = SECONDARY_LABELS.get((t, r["outcome"]), f"{t.upper()} {r['outcome']}")
            out.append(
                f"| {label} | {TERM_LABEL.get(r['term'], r['term'])} | {nev(r1)} | {ci(r1)} | {ci(r2)} |"
            )
    out.append("")
    # S2 change model below the event gate: band counts
    gated = [r for r in run.rows("s2", model="m1") if r["term"].startswith("band_")]
    if gated:
        ev = run.row("s2", outcome=gated[0]["outcome"], term="events", model="m1")
        out.append(
            f"**S2 from 72 months** had {ev['events'] if ev else '—'} replacements, below the "
            "20-event gate (`tkr.min_events`), so no model was fitted. Replacements by step band at "
            "48 months: "
            + "; ".join(
                f"{BAND_LABEL[r['term'].removeprefix('band_')]}: {r['events']} of {r['n']}"
                for r in gated
            )
            + "."
        )
        out.append("")
    # descriptive progression by band
    out.append(
        "**KL transitions by step band at 48 months** (`descriptives.csv`; read knees, replacement counted as KL 4):"
    )
    out.append("")
    out.append("| Transition | " + " | ".join(BAND_LABEL[b] for b in BANDS) + " |")
    out.append("|---|" + "---|" * len(BANDS))
    trans = [r for r in run.desc if r["table"] == "transitions_by_band"]
    for name in dict.fromkeys(r["outcome"] for r in trans):
        cells = []
        for b in BANDS:
            r = next((x for x in trans if x["outcome"] == name and x["level"] == b), None)
            cells.append(
                "—"
                if r is None
                else f"{r['events']} / {n0(int(r['n']))} ({int(r['events']) / int(r['n']):.0%})"
            )
        shown = "any ≥ 1 grade" if name == "any" else name.replace(">", " → ").replace("-", "–")
        out.append(f"| {shown} | " + " | ".join(cells) + " |")
    out.append("")
    out.append(
        "**JSW window:** the FNIH 0.7 mm threshold was set for 24–48 months of change; here it "
        "is applied to 48 → 96 months (four years) and 72 → 96 months (two years), so the share "
        "of progressors is not comparable with FNIH's and the two S3b windows are not comparable "
        "with each other."
    )
    out.append("")
    k, m = tally(run, SECONDARY)
    out.append(
        f"**CIs that exclude the null:** {k} of the {m} secondary estimates (S1–S4, both models, "
        f"linear and change terms). About {0.05 * m:.1f} would be expected by chance at 95%."
    )
    hits = [r for r in ci_rows(run, SECONDARY) if excludes_null(r)]
    if hits:
        out.append("")
        for r in hits:
            out.append(
                f"- {SECONDARY_LABELS.get((r['table'], r['outcome']), r['outcome'])}, "
                f"{TERM_LABEL.get(r['term'], r['term'])}, Model {r['model'][1]}: {ci(r)}"
            )
    out.append("")
    return out


def reverse_section(run: Run) -> list[str]:
    out = [
        "### Reverse: knee OA → steps at 72 months",
        "",
        "Difference in steps/day at 72 months (thousands), adjusted for steps at 48 months and "
        'wear at both waves; one row per person. "People with it" is the number with the '
        "exposure.",
        "",
        "| Exposure | People / people with it | Model 1 | Model 2 |",
        "|---|---|---|---|",
    ]
    labels = {
        "r1": "R1, new ROA or KL worsening in either knee, 36 → 48 months (preceding)",
        "r2": "R2, new ROA or knee replacement in either knee, 48 → 72 months (concurrent)",
    }
    for t in ("r1", "r2"):
        for term in dict.fromkeys(r["term"] for r in run.tables.get(t, [])):
            r1 = run.row(t, term=term, model="m1")
            r2 = run.row(t, term=term, model="m2")
