# ------------------------------------------------------------------ reading
def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as fh:
        return list(csv.DictReader(fh))


def num(v: str | None) -> float | None:
    if v is None or v in ("", "NA"):
        return None
    x = float(v)
    return None if math.isnan(x) else x


class Run:
    def __init__(self, folder: Path):
        self.folder = folder
        self.tables = {
            p.stem.removeprefix("table_"): read_csv(p) for p in sorted(folder.glob("table_*.csv"))
        }
        self.flow = {(r["sample"], r["step"]): int(r["n"]) for r in read_csv(folder / "flow.csv")}
        self.desc = read_csv(folder / "descriptives.csv")
        self.info = json.loads((folder / "run_info.json").read_text())
        log = any(r["term"] == "per_log" for r in self.tables.get("p1", []))
        for rows in self.tables.values():
            for r in rows:
                if r["outcome"] in MM_OUTCOMES:
                    r["_kind"] = "mm"
                elif r["table"] in ("r1", "r2") and not log:
                    r["_kind"] = "diff"
                else:
                    r["_kind"] = "ratio"

    def rows(self, table: str, **match: str) -> list[dict[str, str]]:
        return [r for r in self.tables.get(table, []) if all(r[k] == v for k, v in match.items())]

    def row(self, table: str, **match: str) -> dict[str, str] | None:
        rows = self.rows(table, **match)
        return rows[0] if rows else None

    def curve(self, name: str) -> list[dict[str, str]]:
        p = self.folder / f"curve_{name}.csv"
        return read_csv(p) if p.is_file() else []


# ------------------------------------------------------------------ formatting
def n0(x: float | int | None) -> str:
    return "—" if x is None else f"{x:,.0f}"


def minus(text: str) -> str:
    return text.replace("-", "−")


def is_mm(r: dict[str, str]) -> bool:
    return r.get("_kind") == "mm"


def is_steps_diff(r: dict[str, str]) -> bool:
    return r.get("_kind") == "diff"


def ci(r: dict[str, str] | None) -> str:
    if r is None:
        return "—"
    est, lo, hi = num(r["estimate"]), num(r["lo"]), num(r["hi"])
    if est is None:
        return "not fitted"
    if lo is None or hi is None:
        return f"{est:.2f} (ref)" if est == 1 else f"{est:.2f}"
    if is_mm(r):
        return minus(f"{est:+.3f} ({lo:+.3f} to {hi:+.3f})")
    if is_steps_diff(r):
        return minus(f"{est:+.2f} ({lo:+.2f} to {hi:+.2f})")
    return f"{est:.2f} ({lo:.2f}–{hi:.2f})"


def null_value(r: dict[str, str]) -> float:
    return 0.0 if (is_mm(r) or is_steps_diff(r)) else 1.0


def excludes_null(r: dict[str, str]) -> bool | None:
    lo, hi = num(r["lo"]), num(r["hi"])
    if lo is None or hi is None:
        return None
    nv = null_value(r)
    return lo > nv or hi < nv


def nev(r: dict[str, str] | None) -> str:
    if r is None:
        return "—"
    ev = num(r["events"])
    return f"{n0(num(r['n']))}" if ev is None else f"{n0(num(r['n']))} / {n0(ev)}"


def lin_term(run: Run) -> str:
    return (
        "per_log" if any(r["term"] == "per_log" for r in run.tables.get("p1", [])) else "per_1000"
    )


def ci_rows(run: Run, tables: list[str]) -> list[dict[str, str]]:
    out = []
    for t in tables:
        for r in run.tables.get(t, []):
            if r["term"] in ("events", "nonlinear_p") or r["term"].startswith("band_"):
                continue
            if excludes_null(r) is not None:
                out.append(r)
    return out


def tally(run: Run, tables: list[str]) -> tuple[int, int]:
    rows = ci_rows(run, tables)
    return sum(bool(excludes_null(r)) for r in rows), len(rows)


def describe(r: dict[str, str]) -> str:
    return f"{r['table'].upper()} {r['outcome']} {r['term']} ({r['model']})"


